const char * gvec_svg_kind_name(GVEC_Svg_Kind kind) {
  for (size_t i = 0; i < sizeof k_elements / sizeof k_elements[0]; i++) {
    if (k_elements[i].kind == kind) {
      return k_elements[i].name;
    }
  }
  return NULL;
}

GVEC_Svg_Kind gvec_svg_kind_find(const char * name, size_t length) {
  size_t lo = 0, hi = sizeof k_elements / sizeof k_elements[0];
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    int c = strncmp(name, k_elements[mid].name, length);
    if (c == 0 && k_elements[mid].name[length] != 0) {
      c = -1;
    }
    if (c == 0) {
      return k_elements[mid].kind;
    }
    if (c < 0) {
      hi = mid;
    } else {
      lo = mid + 1;
    }
  }
  return GVEC_SVG_KIND_UNKNOWN;
}

