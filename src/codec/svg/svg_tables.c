bool gvec_svg_is_legacy(const char * name, size_t length) {
  for (size_t i = 0; i < sizeof k_legacy / sizeof k_legacy[0]; i++) {
    if (strlen(k_legacy[i]) == length && memcmp(k_legacy[i], name, length) == 0) {
      return true;
    }
  }
  return false;
}

