bool gvec_svg_is_presentation(GVEC_Svg_Kind kind, const char * name, size_t length) {
  size_t lo = 0, hi = sizeof k_presentation / sizeof k_presentation[0];
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    int c = name_cmp(k_presentation[mid].name, name, length);
    if (c == 0) {
      return mask_has(k_presentation[mid].lo, k_presentation[mid].hi, kind);
    }
    if (c < 0) {
      lo = mid + 1;
    } else {
      hi = mid;
    }
  }
  return false;
}

