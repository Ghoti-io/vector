static bool mask_has(uint64_t lo, uint64_t hi, GVEC_Svg_Kind kind) {
  unsigned bit = (unsigned) kind;
  return bit < 64 ? ((lo >> bit) & 1) != 0 : ((hi >> (bit - 64)) & 1) != 0;
}

/* Compare a table name with a name of `length` bytes that is not NUL-terminated. */
static int name_cmp(const char * row, const char * name, size_t length) {
  int c = strncmp(row, name, length);
  if (c != 0) {
    return c;
  }
  return row[length] == 0 ? 0 : 1;
}

GVEC_Svg_Grammar gvec_svg_grammar_for(GVEC_Svg_Kind kind, const char * name, size_t length) {
  size_t lo = 0, hi = sizeof k_attributes / sizeof k_attributes[0];
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    if (name_cmp(k_attributes[mid].name, name, length) < 0) {
      lo = mid + 1;
    } else {
      hi = mid;
    }
  }
  for (size_t i = lo; i < sizeof k_attributes / sizeof k_attributes[0] && name_cmp(k_attributes[i].name, name, length) == 0; i++) {
    if (mask_has(k_attributes[i].lo, k_attributes[i].hi, kind)) {
      return (GVEC_Svg_Grammar) k_attributes[i].grammar;
    }
  }
  return GVEC_SVG_GRAMMAR_NONE;
}

