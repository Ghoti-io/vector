const char * gvec_svg_property_name(GVEC_Svg_Property property) {
  return (unsigned) property < GVEC_SVG_PROP_COUNT ? gvec_svg_prop_rows[property].name : NULL;
}

bool gvec_svg_property_find(const char * name, size_t length, GVEC_Svg_Property * out) {
  size_t lo = 0, hi = GVEC_SVG_PROP_COUNT;
  if (!name || !out) {
    return false;
  }
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    const char * row = gvec_svg_prop_rows[mid].name;
    int c = strncmp(name, row, length);
    if (c == 0 && row[length] != 0) {
      c = -1;
    }
    if (c == 0) {
      *out = (GVEC_Svg_Property) mid;
      return true;
    }
    if (c < 0) {
      hi = mid;
    } else {
      lo = mid + 1;
    }
  }
  return false;
}
